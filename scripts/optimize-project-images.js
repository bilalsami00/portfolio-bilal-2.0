/**
 * Generates lightweight WebP variants for project screenshots in public/projects
 * and writes data/projectImageVariants.ts. Originals are left untouched.
 *
 * sharp is intentionally not a project dependency. Run with:
 *   npx --yes --package=sharp@0.33 node scripts/optimize-project-images.js
 * or with NODE_PATH pointing at a node_modules folder that contains sharp.
 *
 * Variants per screenshot:
 *   cover - 16:10 crop from the top, for standard project cards
 *   tall  - top of the page up to a 1:3 ratio, for spotlight / featured media
 *   full  - the whole screenshot at 1280px wide, for the case-study modal
 */
const fs = require("fs");
const path = require("path");

let sharp;
try {
  sharp = require("sharp");
} catch (error) {
  console.error(
    "sharp is required. Run: npx --yes --package=sharp@0.33 node scripts/optimize-project-images.js"
  );
  process.exit(1);
}

const root = path.join(__dirname, "..");
const projectsDir = path.join(root, "public", "projects");
const manifestFile = path.join(root, "data", "projectImageVariants.ts");
const OUTPUT_DIR = "optimized";
const MAX_WEBP_DIMENSION = 16383;

const toPublicPath = (absolute) =>
  `/${path.relative(path.join(root, "public"), absolute).split(path.sep).join("/")}`;

const listScreenshots = () =>
  fs
    .readdirSync(projectsDir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .flatMap((dir) =>
      fs
        .readdirSync(path.join(projectsDir, dir.name))
        .filter((file) => /\.(png|jpe?g)$/i.test(file))
        .map((file) => path.join(projectsDir, dir.name, file))
    );

const writeVariant = async (input, output, { width, cropHeight, quality }) => {
  const meta = await sharp(input, { limitInputPixels: false }).metadata();
  const scale = width / meta.width;
  const targetHeight = Math.min(
    Math.round(meta.height * scale),
    cropHeight || Number.MAX_SAFE_INTEGER,
    MAX_WEBP_DIMENSION
  );
  const sourceHeight = Math.min(meta.height, Math.round(targetHeight / scale));

  await sharp(input, { limitInputPixels: false })
    .extract({ left: 0, top: 0, width: meta.width, height: sourceHeight })
    .resize({ width, height: targetHeight, fit: "fill" })
    .webp({ quality, effort: 5 })
    .toFile(output);

  return { src: toPublicPath(output), width, height: targetHeight };
};

const run = async () => {
  const manifest = {};

  for (const file of listScreenshots()) {
    const dir = path.join(path.dirname(file), OUTPUT_DIR);
    fs.mkdirSync(dir, { recursive: true });
    const base = path.basename(file, path.extname(file));
    const out = (suffix) => path.join(dir, `${base}-${suffix}.webp`);

    const cover = [];
    for (const width of [640, 1200]) {
      cover.push(
        await writeVariant(file, out(`cover-${width}`), {
          width,
          cropHeight: Math.round((width * 10) / 16),
          quality: 76,
        })
      );
    }

    const tall = [];
    for (const width of [640, 1280]) {
      tall.push(
        await writeVariant(file, out(`tall-${width}`), {
          width,
          cropHeight: width * 3,
          quality: 76,
        })
      );
    }

    const full = await writeVariant(file, out("full-1280"), {
      width: 1280,
      quality: 80,
    });

    manifest[toPublicPath(file)] = { cover, tall, full };
    console.log(`optimized ${toPublicPath(file)}`);
  }

  const body = `/* eslint-disable import/prefer-default-export */
/**
 * Generated by scripts/optimize-project-images.js. Do not edit by hand.
 * Maps an original screenshot path to lighter WebP variants.
 */
import type { ProjectImageVariantSet } from "../utilities/projectImages";

export const projectImageVariants: Record<string, ProjectImageVariantSet> = ${JSON.stringify(
    manifest,
    null,
    2
  )};
`;

  fs.writeFileSync(manifestFile, body);
  console.log(`wrote ${path.relative(root, manifestFile)}`);
};

run().catch((error) => {
  console.error(error);
  process.exit(1);
});
